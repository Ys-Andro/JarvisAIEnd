package com.example.jarvisai.ui.mascot

/**
 * The 10 official facial and emotional expressions of the JARVIS 3.0 mascot.
 */
enum class MascotExpression {
    FELIZ,      // Happy: Inverted curved arcs (⌒ ⌒), cheerful tilt, bright cyan
    CURIOSO,    // Curious: Large round eyes, head tilt, holographic '?'
    PENSANDO,   // Thinking: Side-up look, hand to chin, intermittent cyan halo
    SORPRENDIDO,// Surprised: Dilated eyes, head back, arms raised, '!' mark
    TRISTE,     // Sad: Slanted downward eyes, lowered head, dim cyan
    ENOJADO,    // Angry: Slanted eyes, firm posture, discreet warning red spark
    ASOMBRADO,  // Amazed: Big sparkling eyes, expansive arms, bright glow
    SERENO,     // Serene: Calm semicircular gentle eyes, stable stance
    DORMIDO,    // Sleeping: Closed eyes, slow breathing, floating Zzz
    EMOCIONADO  // Excited: 4-pointed star eyes (✦ ✦), raised arms, radiant sparkles
}
